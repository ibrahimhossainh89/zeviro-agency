export const SOCIALS = [
  { key: 'linkedin', label: 'LinkedIn' },
  { key: 'x', label: 'X (Twitter)' },
  { key: 'facebook', label: 'Facebook' },
  { key: 'instagram', label: 'Instagram' },
  { key: 'youtube', label: 'YouTube' },
  { key: 'whatsapp', label: 'WhatsApp' },
  { key: 'github', label: 'GitHub' },
];

export function SocialGlyph({ name, className = 'h-4 w-4' }) {
  return (
    <svg viewBox="0 0 24 24" className={className} fill="currentColor" aria-hidden="true">
      <path d={PATHS[name]} />
    </svg>
  );
}

// WhatsApp may be stored as a phone number → turn into a wa.me link
const toHref = (key, v) => (key === 'whatsapp' && !/^https?:/.test(v) ? `https://wa.me/${v.replace(/[^\d]/g, '')}` : v);

export default function SocialIcons({ className, size = 'md' }) {
  const { settings } = useSite();
  const s = settings.socials || {};
  const items = SOCIALS.filter(({ key }) => s[key]);
  if (!items.length) return null;
  return (
    <ul className={cn('flex flex-wrap gap-2', className)} aria-label="Social media">
      {items.map(({ key, label }) => (
        <li key={key}>
          <a
            href={toHref(key, s[key])}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`Zeviro on ${label}`}
            title={label}
            className={cn('flex items-center justify-center rounded-xl border border-ink-600 text-slate-400 transition hover:-translate-y-0.5 hover:border-brand-500 hover:text-white', size === 'sm' ? 'h-8 w-8' : 'h-10 w-10')}
          >
            <SocialGlyph name={key} className={size === 'sm' ? 'h-3.5 w-3.5' : 'h-4 w-4'} />
          </a>
        </li>
      ))}
    </ul>
  );
}
